#!/usr/bin/env bash
# Builds the AmF X1 Windows .msi (Microsoft Store MSI submission) with wixl (msitools).
# Usage: scripts/build-msi.sh [VERSION]   (default 1.27.0.0)
# Writes install/windows/amfx1.wxs (generated from the package folder) and releases/windows/AmF-X1-<VERSION>-x64.msi.
# GUIDs are uuid5 of fixed strings / relative paths, so rebuilding gives the same component GUIDs; the ProductCode depends
# on the version, the UpgradeCode never changes.
set -euo pipefail
VERSION="${1:-1.27.0.0}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PKG="$ROOT/dist/windows/AmF-X1-$VERSION-windows-x64"
WXS="$ROOT/install/windows/amfx1.wxs"
OUT="$ROOT/releases/windows/AmF-X1-$VERSION-x64.msi"
[ -d "$PKG" ] || { echo "missing package folder $PKG" >&2; exit 1; }
# Refuse to package anything that looks private.
BAD=$(cd "$PKG" && find . -type f \( -iname '*.pem' -o -iname '*.key' -o -iname '*.pfx' -o -iname '*.p12' -o -iname '*.jks' \
  -o -iname '*.keystore' -o -iname '.env*' -o -iname '*token*' -o -iname '*.log' -o -iname '*secret*' -o -iname 'settings*.json' \) )
[ -z "$BAD" ] || { echo "private-looking files in package, refusing:" >&2; echo "$BAD" >&2; exit 1; }
python3 -I - "$PKG" "$VERSION" "$WXS" <<'PY'
import os, sys, uuid, hashlib
from xml.sax.saxutils import quoteattr as q
pkg, version, wxs = sys.argv[1:]
NS = uuid.UUID("5b0e7c2a-2f3d-4c55-9a41-6d8f1e0a7b31")      # fixed namespace for AmF X1 MSI GUIDs
UPGRADE = "8F3C2B71-4E6A-4D2F-9B58-1A7E0C9D3F64"            # fixed forever: lets new versions replace old ones
g = lambda s: str(uuid.uuid5(NS, s)).upper()
ident = lambda p, pre: pre + hashlib.sha1(p.encode()).hexdigest()[:20]
lines, comps = [], []
def walk(rel, depth):
    full = os.path.join(pkg, rel)
    for name in sorted(os.listdir(full)):
        r = os.path.join(rel, name) if rel else name
        f = os.path.join(pkg, r)
        ind = "  " * depth
        if os.path.isdir(f):
            lines.append(f'{ind}<Directory Id="{ident(r,"d")}" Name={q(name)}>')
            walk(r, depth + 1)
            lines.append(f'{ind}</Directory>')
        elif os.path.isfile(f):
            rp = r.replace(os.sep, "/")
            cid = ident(rp, "c")
            comps.append(cid)
            lines.append(f'{ind}<Component Id="{cid}" Guid="{g("file:"+rp)}" Win64="yes">')
            fid = "amixos_exe" if rp == "amixos.exe" else ident(rp, "f")
            lines.append(f'{ind}  <File Id="{fid}" Name={q(name)} Source={q(f)} KeyPath="yes"/>')
            lines.append(f'{ind}</Component>')
walk("", 6)
body = "\n".join(lines)
refs = "\n".join(f'      <ComponentRef Id="{c}"/>' for c in comps)
xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/build-msi.sh from the package folder; edit the script, not this file. -->
<Wix xmlns="http://schemas.microsoft.com/wix/2006/wi">
  <Product Id="{g("product:"+version)}" Name="AmF X1" Language="1033" Version="{version}" Manufacturer="AMFB Audio" UpgradeCode="{UPGRADE}">
    <Package InstallerVersion="500" Compressed="yes" InstallScope="perMachine" Description="AmF X1 {version}" Manufacturer="AMFB Audio"/>
    <Media Id="1" Cabinet="amfx1.cab" EmbedCab="yes"/>
    <MajorUpgrade DowngradeErrorMessage="A newer version of AmF X1 is already installed."/>
    <Icon Id="amfx1.ico" SourceFile={q(os.path.join(pkg,"amixos.exe"))}/>
    <Property Id="ARPPRODUCTICON" Value="amfx1.ico"/>
    <Property Id="ARPNOMODIFY" Value="1"/>
    <Property Id="ARPNOREPAIR" Value="1"/>
    <Directory Id="TARGETDIR" Name="SourceDir">
      <Directory Id="ProgramFiles64Folder">
        <Directory Id="INSTALLDIR" Name="AmF X1">
{body}
        </Directory>
      </Directory>
      <Directory Id="ProgramMenuFolder">
        <Component Id="StartMenuShortcut" Guid="{g("shortcut:startmenu")}" Win64="yes">
          <Shortcut Id="AmfX1Shortcut" Name="AmF X1" Description="AmF X1 console" Target="[INSTALLDIR]amixos.exe" WorkingDirectory="INSTALLDIR" Icon="amfx1.ico"/>
          <RegistryValue Root="HKLM" Key="Software\\AMFB Audio\\AmF X1" Name="InstallDir" Type="string" Value="[INSTALLDIR]" KeyPath="yes"/>
          <RegistryValue Root="HKLM" Key="Software\\AMFB Audio\\AmF X1" Name="Version" Type="string" Value="{version}"/>
        </Component>
      </Directory>
    </Directory>
    <Feature Id="Main" Title="AmF X1" Level="1">
{refs}
      <ComponentRef Id="StartMenuShortcut"/>
    </Feature>
  </Product>
</Wix>
'''
open(wxs, "w").write(xml)
print(len(comps), "files")
PY
mkdir -p "$(dirname "$OUT")"
wixl -a x64 -o "$OUT" "$WXS"
ls -l "$OUT"
